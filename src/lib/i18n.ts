export function localizeService<
  T extends {
    title: string;
    description: string;
    title_i18n?: unknown;
    description_i18n?: unknown;
  },
>(service: T, locale: Locale): T {
  const localized = (value: unknown, fallback: string) => {
    if (typeof value !== "object" || value === null || Array.isArray(value))
      return fallback;
    const text = (value as Record<string, unknown>)[locale];
    return typeof text === "string" && text.trim() ? text : fallback;
  };
  return {
    ...service,
    title: localized(service.title_i18n, service.title),
    description: localized(service.description_i18n, service.description),
  };
}
